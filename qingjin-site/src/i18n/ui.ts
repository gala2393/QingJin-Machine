/** `vars` fills `{name}` placeholders, e.g. t(lang, 'home.btnExplore', { models: 107 }). */
export function t(lang: Lang, key: keyof typeof ui['zh'], vars?: Record<string, string | number>): string {
  const s: string = ui[lang]?.[key] ?? ui[defaultLang][key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

export function getLangFromUrl(url: URL): Lang {
  const [, lang] = url.pathname.split('/');
  if (lang in ui) return lang as Lang;
  return defaultLang;
}

export function formatLocaleUrl(lang: Lang, path: string): string {
  const cleanPath = path.startsWith('/') ? path : `/${path}`;
  return `/${lang}${cleanPath}`;
}
